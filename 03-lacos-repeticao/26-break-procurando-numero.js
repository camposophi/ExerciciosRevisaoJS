// EXERCÍCIO 26 - BREAK
// Utilize um for de 1 até 10.
// Quando o número chegar em 6:
// mostre "Número encontrado: 6"
// e interrompa o laço utilizando break.

// Escreva sua solução abaixo:

for (let numero = 1; numero <= 10; numero++){
    if(numero === 6){
        console.log("Número encontrado:" + numero);
        break;
        }   
}
